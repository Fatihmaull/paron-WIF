#!/usr/bin/env node
// Exports Foundry ABIs into packages/core/src/abi/index.ts as typed `as const` arrays for viem.
// Linked-library events and errors (ParonClobLib, ParonSettlementLib) are merged into the
// ParonExchangeDesk ABI because their logs are emitted from the desk's address.
// Usage: (cd contracts && forge build) && node scripts/export-abis.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const target = join(root, "packages", "core", "src", "abi", "index.ts");
const check = process.argv.includes("--check");

const CONTRACTS = {
  wifToken: "WifTokenMock",
  usdg: "UsdgMock",
  paronSeriesToken: "ParonSeriesToken",
  wifFlywheelVault: "WifFlywheelVault",
  wifSlaJury: "WifSlaJury",
  paronExchangeDesk: "ParonExchangeDesk",
};
const DESK_LIBRARIES = ["ParonClobLib", "ParonSettlementLib"];

function load(name) {
  const file = join(out, `${name}.sol`, `${name}.json`);
  if (!existsSync(file)) {
    console.error(`missing ${file}. Run (cd contracts && forge build) first.`);
    process.exit(1);
  }
  return JSON.parse(readFileSync(file, "utf8")).abi;
}

function key(item) {
  return `${item.type}:${item.name ?? ""}:${(item.inputs ?? []).map((i) => i.type).join(",")}`;
}

const sections = [];
for (const [exportName, contract] of Object.entries(CONTRACTS)) {
  let abi = load(contract);
  if (contract === "ParonExchangeDesk") {
    const seen = new Set(abi.map(key));
    for (const lib of DESK_LIBRARIES) {
      for (const item of load(lib)) {
        if ((item.type === "event" || item.type === "error") && !seen.has(key(item))) {
          abi = [...abi, item];
          seen.add(key(item));
        }
      }
    }
  }
  sections.push(`export const ${exportName}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`);
}

const body = `// Generated by scripts/export-abis.mjs from contracts/out. Do not edit by hand.
// Regenerate: (cd contracts && forge build) && npm run abi
/* eslint-disable */

${sections.join("\n")}`;

if (check) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== body) {
    console.error("ABI drift: packages/core/src/abi/index.ts is out of date. Run `npm run abi`.");
    process.exit(1);
  }
  console.log("ABIs up to date.");
} else {
  writeFileSync(target, body);
  console.log(`wrote ${target}`);
}
